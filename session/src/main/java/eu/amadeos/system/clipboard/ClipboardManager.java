package eu.amadeos.system.clipboard;

import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.concurrent.atomic.AtomicLong;
import java.util.function.Supplier;
import java.util.logging.Logger;

/**
 * What the clipboard manager does when a selection changes hands, apart from X11 and Swing.
 *
 * <ul>
 *   <li>A program copies: the manager reads the copy at once and puts it at the top of the history, unless
 *       the copy is marked as a password ({@link #SECRET_TARGETS}) or recording is paused.</li>
 *   <li>The program that copied closes: X11 keeps no data of its own, so the copy would be gone. With "keep"
 *       on, the manager takes the clipboard over and offers the copy it read.</li>
 *   <li>A program about to close asks the manager to save the clipboard ({@code SAVE_TARGETS} of the
 *       freedesktop.org clipboard manager convention): the manager reads it and takes it over right away.</li>
 *   <li>With "primary" on, selected text is recorded too and put on the clipboard once the mouse button is
 *       released.</li>
 * </ul>
 *
 * <p>All methods except {@link #arrived(Selection, boolean)} run on one worker thread, one after the other.
 */
public final class ClipboardManager {
    private static final Logger LOGGER = Logger.getLogger(ClipboardManager.class.getName());

    /**
     * Formats by which password managers mark a copy that must not be kept: KDE's hint (KeePassXC sets it)
     * and the nspasteboard.org types.
     */
    public static final Set<String> SECRET_TARGETS = Set.of(
            "x-kde-passwordManagerHint",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType");

    /** A change of a selection's owner, as the X server reported it. */
    public record OwnerChange(Selection selection, long owner, boolean gone, long sequence) {
    }

    private final ClipboardHistory history;
    private final SystemClipboards clipboards;
    private final SelectionProbe probe;
    private final Supplier<Instant> clock;
    private final AtomicLong primarySequence = new AtomicLong();
    private volatile ClipboardSettings settings;
    private volatile boolean paused;
    /** The window through which this program owns the clipboard, known after the first take-over. */
    private long ownWindow;
    /** The history's entry for what is on the clipboard now, or null if it is not in the history. */
    private ClipEntry current;

    public ClipboardManager(ClipboardHistory history, SystemClipboards clipboards, SelectionProbe probe,
                            ClipboardSettings settings, Supplier<Instant> clock) {
        this.history = history;
        this.clipboards = clipboards;
        this.probe = probe;
        this.clock = clock;
        apply(settings);
    }

    /**
     * Called on the X thread when the server reports a change; numbers it, so that a selection that is still
     * being made can be told apart from a newer one.
     */
    public OwnerChange arrived(Selection selection, long owner, boolean gone) {
        long sequence = selection == Selection.PRIMARY ? primarySequence.incrementAndGet() : 0;
        return new OwnerChange(selection, owner, gone, sequence);
    }

    /**
     * Handles a change; false means "not yet": the selection is still being made with the mouse, ask again
     * a little later.
     */
    public boolean handle(OwnerChange change) {
        return change.selection() == Selection.CLIPBOARD ? clipboardChanged(change) : primaryChanged(change);
    }

    // --8<-- [start:changed]
    private boolean clipboardChanged(OwnerChange change) {
        if (!settings.history() || paused) {
            current = null;
            return true;
        }
        if (change.gone()) {
            // The program that copied has closed (or its window is gone): offer its copy ourselves.
            if (settings.keep() && current != null && history.contains(current) && probe.owner(Selection.CLIPBOARD) == 0) {
                LOGGER.fine(() -> "Owner of the clipboard closed, taking over " + current);
                take(current);
            }
            return true;
        }
        if (change.owner() == 0) {
            // Cleared on purpose (a password manager does that after a while): leave it empty.
            current = null;
            return true;
        }
        if (ownWindow != 0 && change.owner() == ownWindow) return true;
        current = record(Selection.CLIPBOARD).orElse(null);
        return true;
    }
    // --8<-- [end:changed]

    private boolean primaryChanged(OwnerChange change) {
        if (!settings.history() || !settings.primary() || paused || change.gone() || change.owner() == 0) return true;
        if (change.sequence() != primarySequence.get()) return true; // a newer selection follows
        if (probe.buttonDown()) return false;
        if (ownWindow != 0 && change.owner() == ownWindow) return true;
        if (isSecret(probe.targets(Selection.PRIMARY))) return true;
        Optional<ClipEntry> read = clipboards.read(Selection.PRIMARY)
                .filter(e -> e.text() != null && !e.text().isBlank())
                .map(e -> ClipEntry.text(e.text(), e.copied()));
        if (read.isEmpty() || read.get().sameContent(current)) return true;
        history.add(read.get()).ifPresent(this::take);
        return true;
    }

    /**
     * A program asks for the clipboard to be saved before it closes; true when the manager now offers it.
     * Saves even while the history is off or paused (the program asked), but never a password.
     */
    // --8<-- [start:save]
    public boolean save() {
        long owner = probe.owner(Selection.CLIPBOARD);
        if (owner == 0) return false;
        if (owner == ownWindow) return true;
        Optional<ClipEntry> entry = record(Selection.CLIPBOARD);
        if (entry.isEmpty()) return false;
        take(entry.get());
        return true;
    }
    // --8<-- [end:save]

    // --8<-- [start:record]
    private Optional<ClipEntry> record(Selection selection) {
        List<String> targets = probe.targets(selection);
        if (isSecret(targets)) {
            LOGGER.fine("Copy marked as a password, not recorded");
            return Optional.empty();
        }
        Optional<ClipEntry> entry = clipboards.read(selection);
        if (entry.isEmpty()) return Optional.empty();
        if (!settings.history() || paused) return entry;
        return history.add(entry.get());
    }

    static boolean isSecret(List<String> targets) {
        return targets.stream().anyMatch(SECRET_TARGETS::contains);
    }
    // --8<-- [end:record]

    /** Puts an entry from the history on the clipboard and moves it to the top. */
    public void choose(ClipEntry entry) {
        ClipEntry chosen = entry.copiedAt(clock.get());
        history.remove(entry);
        take(history.add(chosen).orElse(chosen));
    }

    private void take(ClipEntry entry) {
        clipboards.own(entry);
        ownWindow = probe.owner(Selection.CLIPBOARD);
        current = entry;
    }

    public void remove(ClipEntry entry) {
        history.remove(entry);
        if (entry == current) current = null;
    }

    public void clear() {
        history.clear();
        current = null;
    }

    public boolean paused() {
        return paused;
    }

    public void setPaused(boolean paused) {
        this.paused = paused;
        LOGGER.info(paused ? "Clipboard recording paused" : "Clipboard recording resumed");
    }

    public ClipboardSettings settings() {
        return settings;
    }

    /** New settings from the Settings; turning the history off forgets it. */
    public void apply(ClipboardSettings settings) {
        this.settings = settings;
        history.setLimit(settings.size());
        if (!settings.history()) clear();
    }

    public ClipboardHistory history() {
        return history;
    }
}
